import fs from 'node:fs';
import path from 'node:path';
import { toId } from 'storybook/internal/csf';

// Generates one MDX docs page per Markdown file in documentation/ (plus
// AGENTS.md) so Storybook shows the docs without duplicating them. The .md
// files stay the source of truth: each page imports its file with `?raw`,
// so edits show up live. Only adding/removing/renaming a doc needs a
// Storybook restart. Output is gitignored.

const ROOT = path.resolve(import.meta.dirname, '../..');
const OUT = path.join(import.meta.dirname, 'generated');

interface DocEntry {
    source: string; // repo-relative path, e.g. documentation/features/05-localization.md
    title: string; // Storybook title, e.g. Documentation/Features/05 Localization (4 languages)
}

function listMarkdown(dir: string): string[] {
    return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) return listMarkdown(full);
        return entry.name.endsWith('.md') ? [full] : [];
    });
}

function heading(file: string): string {
    const match = fs.readFileSync(file, 'utf8').match(/^#\s+(.+)$/m);
    return match ? match[1] : path.basename(file, '.md');
}

// Storybook splits titles on "/", and its ids keep characters like "·",
// so keep titles to plain words.
const clean = (text: string) =>
    text
        .replace(/^Prototype:\s*/, '')
        .replace(/\s*·\s*/g, ' ')
        .replace(/\s+\/\s+/g, ' & ') // "Events / Services"
        .replace(/(^|\s)\/(?=\w)/g, '$1') // "/find page" → "find page"
        .replace(/\//g, '-') // "shadcn/ui" → "shadcn-ui"
        .replace(/[`"]/g, '')
        .trim();

function titleFor(source: string): string {
    const special: Record<string, string> = {
        'AGENTS.md': 'Documentation/Agents Guide',
        'documentation/README.md': 'Documentation/Overview',
        'documentation/getting-started.md': 'Documentation/Getting Started',
    };
    if (special[source]) return special[source];

    const folders = path
        .dirname(source)
        .split('/')
        .slice(1) // drop "documentation"
        .map((part) => part[0].toUpperCase() + part.slice(1));
    return [
        'Documentation',
        ...folders,
        clean(heading(path.join(ROOT, source))),
    ].join('/');
}

export function generateDocPages(): void {
    const sources = [
        'AGENTS.md',
        ...listMarkdown(path.join(ROOT, 'documentation')).map((f) =>
            path.relative(ROOT, f).split(path.sep).join('/')
        ),
    ].sort();

    const entries: DocEntry[] = sources.map((source) => ({
        source,
        title: titleFor(source),
    }));

    fs.rmSync(OUT, { recursive: true, force: true });
    fs.mkdirSync(OUT, { recursive: true });

    // source path -> Storybook docs id, used to rewrite links between docs.
    const docMap = Object.fromEntries(
        entries.map((e) => [e.source, toId(e.title, 'Docs')])
    );
    fs.writeFileSync(
        path.join(OUT, 'doc-map.json'),
        JSON.stringify(docMap, null, 2) + '\n'
    );

    for (const { source, title } of entries) {
        const relative = path
            .relative(OUT, path.join(ROOT, source))
            .split(path.sep)
            .join('/');
        const file = path.join(OUT, `${source.replace(/[/.]/g, '_')}.mdx`);
        fs.writeFileSync(
            file,
            [
                `{/* Generated by .storybook/docs/generate.ts from ${source}. Do not edit. */}`,
                `import { Meta } from '@storybook/addon-docs/blocks';`,
                `import { DocPage } from '../DocPage';`,
                `import docMap from './doc-map.json';`,
                `import content from '${relative}?raw';`,
                '',
                `<Meta title=${JSON.stringify(title)} />`,
                '',
                `<DocPage source=${JSON.stringify(source)} content={content} docMap={docMap} />`,
                '',
            ].join('\n')
        );
    }
}
